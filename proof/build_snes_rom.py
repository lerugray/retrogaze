#!/usr/bin/env python3
"""Build the SNES proof viewer ROM (LoROM, 128 KiB) for one exported scene.

    build_snes_rom.py --in-dir D --name N --out X.sfc [--ca65 ca65] [--ld65 ld65]

Reads D/N.vram.json (the allocator's VRAM map, the PPU register values and the exported file names) and the
files it names: N.bgK.4bpp / N.bg3.2bpp, N.bgK.map, N.obj.4bpp, N.cgram (512 B), N.oam (544 B). Writes
scene.inc, assembles proof/snes/viewer.s with ca65 --cpu 65816 and links it with proof/snes/lorom.cfg; the
scene files come in by .incbin straight from D. Then it writes the LoROM header checksum. Same inputs and
toolchain -> byte-identical .sfc. Prints "<sha256>  <out>". Standard library only.
"""
import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
VIEWER = HERE / "snes" / "viewer.s"
LINKER_CFG = HERE / "snes" / "lorom.cfg"
ROM_SIZE = 4 * 32768
HEADER = 0x7FC0                                  # LoROM internal header in the file
NAME_RE = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_.-]*$")
REGISTERS = ["BGMODE", "TM", "BG1SC", "BG2SC", "BG3SC", "BG12NBA", "BG34NBA", "OBSEL",
             "BG1HOFS", "BG1VOFS", "BG2HOFS", "BG2VOFS", "BG3HOFS", "BG3VOFS"]
MAX_BYTES = {"bg1_chr": 32768, "bg2_chr": 32768, "bg3_chr": 16384, "obj": 16384}


class SceneError(ValueError):
    pass


def _hex(v: str) -> int:
    if not isinstance(v, str) or not re.fullmatch(r"\$[0-9A-Fa-f]{1,4}", v):
        raise SceneError(f"bad register or address value {v!r}")
    return int(v[1:], 16)


def read_scene(in_dir: Path, name: str) -> dict:
    """Validate vram.json and the files it names; return {regions, registers, files}."""
    if not NAME_RE.match(name):
        raise SceneError(f"scene name {name!r} must match {NAME_RE.pattern}")
    doc = json.loads((in_dir / f"{name}.vram.json").read_text(encoding="utf-8"))
    regions = {k: (_hex(v["word_address"]), int(v["bytes"])) for k, v in doc["regions"].items()}
    regs = {k: _hex(v) for k, v in doc["registers"].items() if k in REGISTERS}
    files = doc["files"]
    for key, size in (("cgram", 512), ("oam", 544)):
        p = in_dir / files[key]
        if not p.is_file() or p.stat().st_size != size:
            raise SceneError(f"{p}: missing or not {size} bytes")
    for region, (word, size) in regions.items():
        key = "obj_chr" if region == "obj" else region
        p = in_dir / files[key]
        if not p.is_file() or p.stat().st_size != size:
            raise SceneError(f"{p}: missing or not the {size} bytes vram.json says")
        if region in MAX_BYTES and size > MAX_BYTES[region]:
            raise SceneError(f"{region} is {size} bytes; the viewer's bank holds {MAX_BYTES[region]}")
        if word * 2 + size > 65536:
            raise SceneError(f"{region} leaves VRAM")
    return {"regions": regions, "registers": regs, "files": files}


def scene_include(name: str, scene: dict) -> str:
    regions, files = scene["regions"], scene["files"]
    lines = [f"; generated by build_snes_rom.py from {name}.vram.json"]
    for layer in ("bg1", "bg2", "bg3"):
        if f"{layer}_chr" in regions:
            up = layer.upper()
            word, size = regions[f"{layer}_chr"]
            lines += [f"HAS_{up} = 1", f'.define SCENE_{up}_CHR "{files[layer + "_chr"]}"',
                      f'.define SCENE_{up}_MAP "{files[layer + "_map"]}"',
                      f"{up}_CHR_VRAM = ${word:04X}", f"{up}_CHR_BYTES = {size}",
                      f"{up}_MAP_VRAM = ${regions[layer + '_map'][0]:04X}"]
    if "obj" in regions:
        word, size = regions["obj"]
        lines += ["HAS_OBJ = 1", f'.define SCENE_OBJ_CHR "{files["obj_chr"]}"', f"OBJ_VRAM = ${word:04X}",
                  f"OBJ_BYTES = {size}"]
    lines += [f'.define SCENE_CGRAM "{files["cgram"]}"', f'.define SCENE_OAM "{files["oam"]}"']
    for reg in REGISTERS:
        lines.append(f"REG_{reg} = ${scene['registers'].get(reg, 0):04X}")
    return "\n".join(lines) + "\n"


def checksum(rom: bytearray) -> None:
    """LoROM header checksum: the 16-bit sum of every byte, with complement $FFFF / checksum $0000 in place."""
    rom[HEADER + 0x1C:HEADER + 0x20] = bytes([0xFF, 0xFF, 0x00, 0x00])
    total = sum(rom) & 0xFFFF
    rom[HEADER + 0x1C:HEADER + 0x20] = (total ^ 0xFFFF).to_bytes(2, "little") + total.to_bytes(2, "little")


def run(cmd: list) -> None:
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError(f"{' '.join(cmd)}\n{proc.stdout}{proc.stderr}")


def build(in_dir, name, out, ca65="ca65", ld65="ld65") -> str:
    """Build the ROM; return its sha256 (hex)."""
    in_dir, out = Path(in_dir).resolve(), Path(out).resolve()
    scene = read_scene(in_dir, name)
    with tempfile.TemporaryDirectory(prefix="rg-snesrom-") as tmp:
        tmp = Path(tmp)
        (tmp / "scene.inc").write_text(scene_include(name, scene), encoding="ascii")
        obj, sfc = tmp / "viewer.o", tmp / "viewer.sfc"
        run([ca65, "--cpu", "65816", "--include-dir", str(tmp), "--bin-include-dir", str(in_dir),
             "-o", str(obj), str(VIEWER)])
        run([ld65, "-C", str(LINKER_CFG), "-o", str(sfc), str(obj)])
        rom = bytearray(sfc.read_bytes())
    if len(rom) != ROM_SIZE:
        raise RuntimeError(f"linked ROM is {len(rom)} bytes, expected {ROM_SIZE}")
    checksum(rom)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(bytes(rom))
    return hashlib.sha256(rom).hexdigest()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--in-dir", required=True, type=Path)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--ca65", default="ca65")
    ap.add_argument("--ld65", default="ld65")
    args = ap.parse_args(argv)
    try:
        digest = build(args.in_dir, args.name, args.out, args.ca65, args.ld65)
    except (SceneError, RuntimeError, OSError, json.JSONDecodeError, KeyError) as exc:
        print(f"build_snes_rom: {exc}", file=sys.stderr)
        return 1
    print(f"{digest}  {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
